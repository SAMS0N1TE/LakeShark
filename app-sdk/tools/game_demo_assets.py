"""Rebuild the tiny original game-template assets; stdlib only, no downloads."""
from pathlib import Path
import struct
import zlib
import subprocess
import sys

SDK=Path(__file__).resolve().parents[1]
def chunk(tag,data):
    return struct.pack('>I',len(data))+tag+data+struct.pack('>I',zlib.crc32(tag+data))
def array(name,data):
    rows=['static const unsigned char %s[] = {'%name]
    rows += ['    '+','.join(str(b) for b in data[i:i+24])+',' for i in range(0,len(data),24)]
    return '\n'.join(rows+['};',''])
def ctext(name,text):
    import json
    return 'static const char '+name+'[] =\n'+ '\n'.join('    '+json.dumps(s) for s in text.splitlines(keepends=True))+';\n'
def main():
    arcade=SDK/'templates/arcade2d'; flight=SDK/'templates/flight3d'
    for folder in (arcade,flight): (folder/'assets').mkdir(parents=True,exist_ok=True)
    art=[['...cc...','..cccc..','.ccffcc.','cccffccc','cccccccc','..cccc..','.cc..cc.','cc....cc'],
         ['...cc...','..cccc..','.ccffcc.','cccffccc','cccccccc','..cccc..','cc....cc','.cc..cc.'],
         ['bbbbbbbb','b888888b','b8bbbb8b','b8b88b8b','b8b88b8b','b8bbbb8b','b888888b','bbbbbbbb']]
    colors={'.':(0,0,0,0),'c':(0,255,255,255),'f':(255,255,255,255),'b':(0,0,170,255),'8':(85,85,85,255)}
    raw=b''.join(b'\0'+b''.join(bytes(colors[art[frame][y][x]]) for frame in range(3) for x in range(8)) for y in range(8))
    png=b'\x89PNG\r\n\x1a\n'+chunk(b'IHDR',struct.pack('>IIBBBBB',24,8,8,6,0,0,0))+chunk(b'IDAT',zlib.compress(raw))+chunk(b'IEND',b'')
    (arcade/'assets/sheet.png').write_bytes(png)
    tune='LTM1\ntempo 132 4\ninst 0 2 38 5 60\ninst 1 1 18 4 40\npattern 0 16\n'
    for row,note,bass in [(0,'C5','C3'),(2,'E5',None),(4,'G5','G3'),(6,'E5',None),(8,'A5','F3'),(10,'G5',None),(12,'E5','G3'),(14,'D5',None)]:
        tune+=f'row {row} {note}/0 '+(bass+'/1' if bass else '...')+' ... ...\n'
    tune+='order 0\nloop 0\n'
    second='LTM1\ntempo 96 4\ninst 0 0 45 20 100\ninst 1 2 20 5 80\npattern 0 16\n'
    for row,note,bass in [(0,'A4','A2'),(4,'C5','F3'),(8,'E5','C3'),(12,'G5','G2')]:
        second+=f'row {row} {note}/0 {bass}/1 ... ...\n'
    second+='pattern 1 16\nrow 0 F5/0 F3/1 ... ...\nrow 4 E5/0 ... ... ...\nrow 8 D5/0 G3/1 ... ...\nrow 12 C5/0 ... ... ...\norder 0 1\nloop 0\n'
    (arcade/'assets/arcade.ltm').write_text(tune)
    (arcade/'assets/night.ltm').write_text(second)
    (arcade/'assets.inc').write_text('/* Generated by tools/game_demo_assets.py. Original CC0 demo art/music. */\n'+array('SHEET_PNG',png)+ctext('TUNE',tune)+ctext('SECOND_TUNE',second))
    obj='# Original CC0 low-poly ship, +y up\nv 0 0 -2\nv -2 0 1\nv 2 0 1\nv 0 0.6 0.5\nv 0 -0.3 1\nf 1 2 4\nf 1 4 3\nf 1 5 2\nf 1 3 5\nf 2 5 4\nf 3 4 5\n'
    (flight/'assets/ship.obj').write_text(obj)
    subprocess.run([sys.executable,str(SDK/'tools/obj2l3.py'),str(flight/'assets/ship.obj'),'--binary','-o',str(flight/'assets/ship.l3m')],check=True)
    (flight/'assets.inc').write_text('/* Generated by tools/game_demo_assets.py. Original CC0 demo mesh. */\n'+array('SHIP_L3M',(flight/'assets/ship.l3m').read_bytes()))
if __name__=='__main__': main()
