/* What the LR2021 would hand LR433 for recordings from rtl_433_tests
   (https://github.com/merbanan/rtl_433_tests): each .cu8 put through a model
   of the chip's OOK or FSK engine at the session's rate (an envelope or a
   discriminator, one decision per bit period with the timing pulled to every
   edge, the session's detector or sync word found, the frame after it), and
   rtl_433's own output for the same recording as what must come out.
   Trailing zero bytes are left off; the test puts them back. */

typedef struct {
    const char *source;
    lr433_in_t kind;
    uint32_t rate, lead;
    uint8_t lead_bits;
    int bits;
    const uint8_t *data;
    int len;
    const char *model;     /* rtl_433's model name, its first characters  */
    const char *id;        /* as rtl_433 prints it                         */
    double kpa, temp_c, humidity;
    long long consumption; /* -1 for none                                 */
} lr433_vec_t;

