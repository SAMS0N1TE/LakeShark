LS_CASE(matches_every_official_test_value)
{
    for (unsigned i = 0; i < sizeof(T) / sizeof(T[0]); i++) {
        const double *t = T[i];
        ls_wmm_field_t f;
        LS_CHECK(ls_wmm_field(t[2], t[3], t[1] * 1000.0, t[0], &f));
        LS_CHECK_MSG(fabs(f.declination - t[4]) < 0.01, "row %u D %.3f want %.2f", i, f.declination, t[4]);
        LS_CHECK_MSG(fabs(f.inclination - t[5]) < 0.01, "row %u I %.3f want %.2f", i, f.inclination, t[5]);
        LS_CHECK_MSG(fabs(f.north_nt - t[6]) < 1.0, "row %u X %.1f want %.1f", i, f.north_nt, t[6]);
        LS_CHECK_MSG(fabs(f.east_nt - t[7]) < 1.0, "row %u Y %.1f want %.1f", i, f.east_nt, t[7]);
        LS_CHECK_MSG(fabs(f.down_nt - t[8]) < 1.0, "row %u Z %.1f want %.1f", i, f.down_nt, t[8]);
        LS_CHECK_MSG(fabs(f.total_nt - t[9]) < 1.0, "row %u F %.1f want %.1f", i, f.total_nt, t[9]);
    }
}

LS_CASE(refuses_dates_outside_the_model)
{
    ls_wmm_field_t f;
    LS_CHECK(!ls_wmm_field(43, -71, 0, 2024.9, &f));
    LS_CHECK(!ls_wmm_field(43, -71, 0, 2030.1, &f));
    LS_CHECK(ls_wmm_field(43, -71, 0, ls_wmm_year(2026, 9, 25), &f));
    LS_NEAR(ls_wmm_year(2026, 1, 1), 2026.0, 1e-9);
    LS_NEAR(ls_wmm_year(2028, 12, 31), 2028.0 + 365.0 / 366.0, 1e-9);
}
