#!/usr/bin/env python3
"""The boot splash's world: country outlines as unit vectors, for flash.

Input: an LSOUT1 outlines file (make_outlines.py). Only the countries are
kept, simplified hard and with small islands dropped, because the splash
globe is at most a few hundred dots across and the table lives in the app
image. Each point is a unit vector scaled to int16, so turning the globe is
one 3x3 multiply a point and needs no trigonometry per frame.

usage: make_splash_world.py OUTLINES.lso OUT.c
"""
import math
import struct
import sys

TOL = 0.9           # degrees, Douglas-Peucker
MIN_AREA = 6.0      # square degrees; Iceland, Cuba, Japan's main islands stay


def area(ring):
    a = 0.0
    for i in range(len(ring) - 1):
        a += ring[i][0] * ring[i + 1][1] - ring[i + 1][0] * ring[i][1]
    return abs(a) / 2


def dp(points, tol):
    if len(points) < 3:
        return points
    keep = [False] * len(points)
    keep[0] = keep[-1] = True
    stack = [(0, len(points) - 1)]
    while stack:
        a, b = stack.pop()
        ax, ay = points[a]
        bx, by = points[b]
        dx, dy = bx - ax, by - ay
        norm = math.hypot(dx, dy) or 1e-12
        best, idx = -1.0, -1
        for i in range(a + 1, b):
            px, py = points[i]
            d = abs(dy * px - dx * py + bx * ay - by * ax) / norm
            if d > best:
                best, idx = d, i
        if best > tol:
            keep[idx] = True
            stack.append((a, idx))
            stack.append((idx, b))
    return [p for p, k in zip(points, keep) if k]


def read_lso(path):
    d = open(path, 'rb').read()
    if d[:8] != b'LSOUT1\0\0':
        raise SystemExit('%s: not an LSOUT1 file' % path)
    nr, ng, np_ = struct.unpack_from('<III', d, 8)
    p = 20
    regions = []
    for _ in range(nr):
        code, level, _r, w, s, e, n, first, count, _r2, name = struct.unpack_from('<8sBB4hIHH32s', d, p)
        regions.append((level, first, count))
        p += 58
    rings = []
    for _ in range(ng):
        rings.append(struct.unpack_from('<II', d, p))
        p += 8
    pts = struct.unpack_from('<%dh' % (2 * np_), d, p)
    out = []
    for level, first, count in regions:
        if level != 0:
            continue
        for k in range(first, first + count):
            p0, n = rings[k]
            out.append([(pts[2 * (p0 + j)] / 100.0, pts[2 * (p0 + j) + 1] / 100.0) for j in range(n)])
    return out


def main():
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    rings = []
    for ring in read_lso(sys.argv[1]):
        if area(ring) < MIN_AREA:
            continue
        # A closed ring starts and ends on one point, which gives the line
        # Douglas-Peucker measures against no direction: split it at the
        # point farthest from the start and simplify the two halves.
        far = max(range(len(ring)), key=lambda i: math.hypot(ring[i][0] - ring[0][0], ring[i][1] - ring[0][1]))
        r = dp(ring[:far + 1], TOL)[:-1] + dp(ring[far:], TOL)
        if len(r) >= 4:
            rings.append(r)
    starts, vecs = [], []
    for r in rings:
        starts.append(len(vecs))
        for lon, lat in r:
            la, lo = math.radians(lat), math.radians(lon)
            vecs.append(tuple(int(round(v * 32767)) for v in
                              (math.cos(la) * math.sin(lo), math.sin(la), math.cos(la) * math.cos(lo))))
    starts.append(len(vecs))
    with open(sys.argv[2], 'w', newline='\n') as o:
        o.write('/* Generated by bench/maps/make_splash_world.py from Natural Earth\n'
                '   (public domain). Do not edit. */\n')
        o.write('#include "ls_splash_world.h"\n\n')
        o.write('const uint16_t ls_splash_world_rings = %d;\n' % len(rings))
        o.write('const uint16_t ls_splash_world_start[%d] = {\n' % len(starts))
        for i in range(0, len(starts), 12):
            o.write('    ' + ', '.join('%d' % v for v in starts[i:i + 12]) + ',\n')
        o.write('};\n')
        o.write('const int16_t ls_splash_world_xyz[%d][3] = {\n' % len(vecs))
        for i in range(0, len(vecs), 4):
            o.write('    ' + ' '.join('{%d,%d,%d},' % v for v in vecs[i:i + 4]) + '\n')
        o.write('};\n')
    print('%d rings, %d points, %d bytes' % (len(rings), len(vecs), len(vecs) * 6 + len(starts) * 2))


if __name__ == '__main__':
    main()
