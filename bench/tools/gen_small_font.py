"""Smaller TUI faces for small glass, rendered the way ls_font_mono_14/_16 were.

DejaVu Sans Mono through FreeType with light autohinting and coverage >> 4,
the renderer gen_cyr_font.py proves against the shipped 14 and 16 px tables.
The cell is the hinted advance by the rows every glyph needs, so nothing is
clipped. Writes components/apps/tui/ls_font_mono_<px>.c.

  python bench/tools/gen_small_font.py --freetype PATH/freetype.dll 12 [13 ...]
  python bench/tools/gen_small_font.py --freetype PATH/freetype.dll --measure 14

--measure prints the cell a size gets without writing, to check the rule
against a shipped face (14 px must give 9x16, base 4).
"""
import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from gen_cyr_font import FreeTypeFace, TUI, pack  # noqa: E402


def cell_of(face):
    glyphs = {chr(c): face.render(chr(c), face.px) if c != 32 else None for c in range(32, 127)}
    above = max(g[1] + g[3] for g in glyphs.values() if g)
    below = max(-g[3] for g in glyphs.values() if g)
    right = max(g[0] + g[2] for g in glyphs.values() if g)
    face.ft.FT_Load_Char(face.face, C_ulong(ord("M")), 0)
    adv = int((face.face.contents.glyph.contents.advance.x + 63) // 64)
    return glyphs, (max(adv, right), above + below, below)


def C_ulong(v):
    import ctypes
    return ctypes.c_ulong(v)


def write(px, glyphs, cell):
    cw, ch, base = cell
    name = f"ls_font_mono_{px}"
    dsc, data = [], []
    for c in range(32, 127):
        g = glyphs[chr(c)]
        if g is None:
            dsc.append((len(data), 0, 0, 0, 0))
            continue
        w, h, ox, oy, pix = g
        dsc.append((len(data), w, h, ox, oy))
        data.extend(pack(pix))
    out = [f"/* Generated by bench/tools/gen_small_font.py. Do not edit.",
           f"   DejaVu Sans Mono {px} px, FreeType light autohinting, as ls_font_mono_14.",
           f"   Licence: components/apps/tui/DEJAVU-LICENSE.txt. */",
           '#include "ls_font.h"', "",
           f"static const ls_font_glyph_t dsc_{name}[95] = {{"]
    for c, d in zip(range(32, 127), dsc):
        out.append(f"    {{ {d[0]:5d}, {d[1]:2d}, {d[2]:2d}, {d[3]:3d}, {d[4]:3d} }},  /* 0x{c:02X} */")
    out += ["};", "", f"static const uint8_t bmp_{name}[] = {{"]
    for i in range(0, len(data), 16):
        out.append("    " + ", ".join(f"0x{b:02X}" for b in data[i:i + 16]) + ",")
    out += ["};", "", f"const ls_font_t {name} = {{",
            f"    .dsc = dsc_{name},", f"    .bitmap = bmp_{name},",
            f"    .bitmap_len = {len(data)},", "    .first = 0x20,", "    .count = 95,",
            f"    .cell_w = {cw},", f"    .cell_h = {ch},", f"    .base_line = {base},",
            f'    .name = "{name}",', "};", ""]
    path = TUI / f"{name}.c"
    path.write_text("\n".join(out), encoding="utf-8", newline="\n")
    print(f"{path.name}: {cw}x{ch} base {base}, {len(data)} bytes")


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--freetype", required=True)
    ap.add_argument("--regular", default="C:/Windows/Fonts/DejaVuSansMono.ttf")
    ap.add_argument("--measure", action="store_true")
    ap.add_argument("sizes", nargs="+",
                    help="pixel size, or SIZE:LEAD to add LEAD rows of line spacing above")
    args = ap.parse_args()
    for spec in args.sizes:
        px, _, lead = spec.partition(":")
        px, lead = int(px), int(lead or 0)
        face = FreeTypeFace(args.freetype, args.regular, px)
        glyphs, cell = cell_of(face)
        cell = (cell[0], cell[1] + lead, cell[2])
        if args.measure:
            print(f"{px} px: cell {cell[0]}x{cell[1]} base {cell[2]}")
        else:
            write(px, glyphs, cell)


if __name__ == "__main__":
    sys.exit(main())
