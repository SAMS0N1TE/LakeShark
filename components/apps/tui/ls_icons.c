static inline int ink(int icon, int row, int col)
{
    if (icon <= 0 || icon >= LS_ICON__COUNT) return 0;
    const char *r = ART[icon][row];
    if (!r) return 0;

    for (int i = 0; i < col; i++) if (!r[i]) return 0;
    return r[col] == '#';
}

void ls_icon_draw(tui_surface *sf, tui_rect clip, int x, int y,
                  int icon, uint8_t attr)
{
    if (!sf) return;
    for (int cr = 0; cr < LS_ICON_ROWS; cr++) {
        for (int cc = 0; cc < LS_ICON_COLS; cc++) {
            const int px = cc * 2, py = cr * 2;
            const int q = (ink(icon, py,     px)     ? 1 : 0)
                        | (ink(icon, py,     px + 1) ? 2 : 0)
                        | (ink(icon, py + 1, px)     ? 4 : 0)
                        | (ink(icon, py + 1, px + 1) ? 8 : 0);

            if (!q) continue;
            tui_put_char(sf, clip, x + cc, y + cr, (char)(0x80 | q), attr);
        }
    }
}
